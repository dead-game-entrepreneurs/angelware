#!/usr/bin/env python3
"""Build a CRC-bound PNACH from source; optionally verify the user's retail ELF.

Requires clang, ld.lld, llvm-objcopy and llvm-nm. No game binary is distributed.
The output is deterministic. Build intermediates are kept under ignored work/.
"""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).resolve().parent
BUILD = ROOT / 'work/outrun2006/pnach-build'
ELF_SHA256 = 'be41e98bb0d88a03e436ae2b5cc4d4e1aa90a984b411c5f47824e8d07b31ecdf'
HOOKS = {
 'send': (0x225d48, (0x27bdffc0,0x24020001)),
 'receive': (0x225bd0, (0x27bdff90,0xffb30048)),
 'update': (0x21dd18, (0x27bdffd0,0x3c040060)),
 'discovery': (0x1623e0, (0x27bdf980,0x7fb20650)),
 'auth': (0x151a20, (0x27bdfdc0,0x7fb00230)),
 'create': (0x121330, (0x27bdff70,0x3c020053)),
}
# sceInsock's per-thread staging buffer must include the relay envelope too.
# Keep its limit, EE allocation and IOP RPC allocation consistent. RPC size is
# already calculated from this limit by the original constructor.
RPC_PATCHES = {
 0x13d3f4: (0x24020800, 0x24021000), # li v0,2048 -> li v0,4096
 0x13d408: (0x2404087f, 0x2404107f), # aligned staging allocation + 127
}
def jump(address): return 0x08000000 | (address >> 2)
def run(*args): return subprocess.check_output(args, text=True)
def verify(path):
 data=path.read_bytes()
 if hashlib.sha256(data).hexdigest()!=ELF_SHA256: raise SystemExit('Unsupported retail ELF SHA-256; refusing to build for it')
 offset=lambda a:a-0x100000+0x80
 for name,(address,words) in HOOKS.items():
  if struct.unpack_from('<II',data,offset(address))!=words: raise SystemExit(f'Unexpected {name} prologue')
 for address,(original,_) in RPC_PATCHES.items():
  if struct.unpack_from('<I',data,offset(address))[0]!=original: raise SystemExit(f'Unexpected socket allocation instruction at {address:#x}')
 sndata=offset(0x3bc100)
 assert data[sndata:sndata+4]==b'SNR2'
 assert struct.unpack_from('<I',data,sndata+0x2c)[0]<=0xf00
 assert not any(data[offset(0x3bd000):offset(0x3c0000)]), 'Code cave is not empty'
def assembly():
 lines=['.set noreorder','.set noat','.section .text.hooks,"ax",@progbits','.align 4']
 for name,(address,words) in HOOKS.items():
  lines += [f'.globl hook_{name}',f'hook_{name}:','addiu $sp,$sp,-0x240']
  # Save full 128-bit EE GPRs. LLVM has no R5900 SQ/LQ mnemonic support.
  for reg in range(1,32):
   if reg!=29:lines.append(f'.word {0x7c000000 | (29<<21) | (reg<<16) | (reg*16):#x}')
  lines += ['mfhi $8','sd $8,0x200($sp)','mflo $8','sd $8,0x208($sp)',f'jal shim_{name}','nop','ld $8,0x200($sp)','mthi $8','ld $8,0x208($sp)','mtlo $8']
  for reg in range(1,32):
   if reg not in (2,29):lines.append(f'.word {0x78000000 | (29<<21) | (reg<<16) | (reg*16):#x}')
  lines += ['jr $ra','addiu $sp,$sp,0x240',f'.globl original_{name}',f'original_{name}:']
  lines += [f'.word {w:#x}' for w in words]
  lines += [f'j {address+8:#x}','nop']
 lines += ['.globl send_raw','send_raw:','move $8,$7','li $9,16','j 0x13e918','move $7,$zero',
           '.globl receive_raw','receive_raw:','move $8,$7','addiu $9,$7,16','j 0x13ea88','move $7,$zero']
 return '\n'.join(lines)+'\n'
def build(elf=None):
 if elf:verify(elf)
 BUILD.mkdir(parents=True,exist_ok=True)
 (BUILD/'hooks.S').write_text(assembly())
 flags=['-target','mipsel-unknown-elf','-march=mips3','-mabi=32','-mstack-alignment=16','-mno-abicalls','-fno-pic','-G0','-msoft-float','-ffreestanding','-fno-builtin','-fno-stack-protector','-O2','-Wall','-Wextra','-Werror']
 run('clang',*flags,'-c',str(SOURCE/'transport.c'),'-o',str(BUILD/'transport.o'))
 run('clang',*flags,'-c',str(BUILD/'hooks.S'),'-o',str(BUILD/'hooks.o'))
 run('ld.lld','-m','elf32ltsmip','-T',str(SOURCE/'shim.ld'),str(BUILD/'hooks.o'),str(BUILD/'transport.o'),'-o',str(BUILD/'shim.elf'))
 run('llvm-objcopy','-O','binary',str(BUILD/'shim.elf'),str(BUILD/'shim.bin'))
 symbols={}
 for line in run('llvm-nm','--defined-only',str(BUILD/'shim.elf')).splitlines():
  address,kind,name=line.split();symbols[name]=int(address,16)
 data=(BUILD/'shim.bin').read_bytes();data+=bytes(-len(data)%4)
 lines=['gametitle=OutRun 2006 Coast 2 Coast (USA) [SLUS-21274] [38C16493]',
 '// AngelWare experimental native relay v3 (pre-host pump + RPC buffers). Stock PCSX2 Sockets backend.',
 '// Requires server option native_relay=true. Full reboot after enabling.',
 '// Generated by patches/outrun2006/build.py; state is NOT frozen by patches.',
 '[AngelWare native relay]', 'description=Automatic UDP hosting and native relay; requires AngelWare relay server', 'author=AngelWare']
 for offset in range(0,len(data),4):
  word,=struct.unpack_from('<I',data,offset);lines.append(f'patch=1,EE,{0x3bd000+offset:08X},word,{word:08X}')
 for name,(address,_) in HOOKS.items():
  lines += [f'// {name}',f'patch=1,EE,{address:08X},word,{jump(symbols["hook_"+name]):08X}',f'patch=1,EE,{address+4:08X},word,00000000']
 lines += ['// Socket staging capacity and its matching aligned allocation']
 for address,(_,word) in RPC_PATCHES.items():
  lines.append(f'patch=2,EE,{address:08X},word,{word:08X}')
 output=SOURCE/'SLUS-21274_38C16493.pnach';output.write_text('\n'.join(lines)+'\n')
 import json
 (BUILD/'symbols.json').write_text(json.dumps(symbols,indent=2)+'\n')
 print(f'Built {output.relative_to(ROOT)}: {len(data)} code bytes, state at {symbols["state"]:#x}')
 return symbols
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--elf',type=Path);args=p.parse_args();build(args.elf)
